------ CREATING TABLES
-- AUTOMOVEL
CREATE TABLE AUTOMOVEL(
COD_AUTO		VARCHAR(10),
NOME			VARCHAR(20),
ID_CATEGORIA	VARCHAR(10),
ID_FABRICANTE	VARCHAR(10),
PRIMARY KEY(COD_AUTO)
);

-- UNIDADE
CREATE TABLE UNIDADE(
COD_UNIDADE		VARCHAR(10),
CODAUTO		VARCHAR(10),
COR				VARCHAR(10),
MODELO			VARCHAR(30),
PRIMARY KEY(COD_UNIDADE)
);


------- IMPONDO AS RESTRIÇÕES
ALTER TABLE UNIDADE ADD CONSTRAINT COD_AUTO_FK FOREIGN KEY(CODAUTO) REFERENCES AUTOMOVEL(COD_AUTO);


